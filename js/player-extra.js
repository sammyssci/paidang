function mergePlayerExtra(data) {
  if (!data || !PLAYER_EXTRA) return data;
  (data.playerStats || []).forEach(function (p) {
    var extra = PLAYER_EXTRA[p.id];
    if (!extra) return;
    p.highlights = extra.highlights || [];
    p.articles = extra.articles || [];
  });
  return data;
}

if (typeof window !== 'undefined') {
  window.PLAYER_EXTRA = PLAYER_EXTRA;
  window.mergePlayerExtra = mergePlayerExtra;
}
